/** 坐标附近（200 公里内）最近的候选地区；没有就返回 null。 */
export function nearestRegion(lat: number, lng: number): string | null {
  const rad = Math.PI / 180;
  let best: { name: string; km: number } | null = null;
  for (const [name, [y, x]] of Object.entries(REGION_COORDS)) {
    const a =
      Math.sin(((y - lat) * rad) / 2) ** 2 +
      Math.cos(lat * rad) * Math.cos(y * rad) * Math.sin(((x - lng) * rad) / 2) ** 2;
    const km = 12742 * Math.asin(Math.sqrt(a));
    if (!best || km < best.km) best = { name, km };
  }
  // 冰岛、中国台湾这类按整片地区列的，放宽到 300 公里
  return best && best.km <= (['冰岛', '中国台湾', '北海道'].includes(best.name) ? 300 : 200)
    ? best.name
    : null;
}
